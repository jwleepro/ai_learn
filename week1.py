print("- LLM 은 '다음 토큰 확률표' 를 만드는 함수다.")
print("- 신경망 한 층 = (행렬 W) @ (벡터 x) + (편향 b), 그리고 비선형 함수.")
print("- numpy 핵심: 벡터, 행렬, @ 연산자, broadcasting, softmax.")
